#[derive(Debug, Clone, Copy)]
pub enum RuleClass {
    Berth,
    Cargo,
    Route,
    Telemetry,
    Journal,
    Script,
    Lease,
    Storm,
}

#[derive(Debug, Clone, Copy)]
pub struct RuleSpec {
    pub id: u16,
    pub class: RuleClass,
    pub weight: u8,
    pub mask: u64,
    pub floor: u16,
    pub ceiling: u16,
    pub relation: u8,
}

#[derive(Debug, Clone, Copy)]
pub struct RuleInput {
    pub packet_digest: u64,
    pub manifest_score: u64,
    pub topology_score: u64,
    pub telemetry_score: u64,
    pub symbol_score: u64,
    pub vessel_count: u16,
    pub berth_count: u16,
    pub section_count: u16,
    pub sample_count: u16,
    pub flag_word: u16,
}

#[derive(Debug, Clone, Copy)]
pub struct RuleHit {
    pub rule_id: u16,
    pub severity: u8,
    pub subject: u32,
    pub message_id: u16,
    pub evidence: u64,
}

pub fn evaluate(rule: RuleSpec, input: RuleInput) -> Option<RuleHit> {
    let lane = match rule.class {
        RuleClass::Berth => input.topology_score ^ ((input.berth_count as u64) << 17),
        RuleClass::Cargo => input.manifest_score ^ ((input.vessel_count as u64) << 21),
        RuleClass::Route => input.topology_score.rotate_left(7) ^ input.packet_digest,
        RuleClass::Telemetry => input.telemetry_score ^ ((input.sample_count as u64) << 11),
        RuleClass::Journal => input.packet_digest ^ input.symbol_score.rotate_left(13),
        RuleClass::Script => input.packet_digest.rotate_right(9) ^ input.manifest_score,
        RuleClass::Lease => input.symbol_score ^ input.topology_score.rotate_right(5),
        RuleClass::Storm => input.packet_digest ^ input.telemetry_score.rotate_left(3),
    };
    let population = input.vessel_count
        .wrapping_add(input.berth_count)
        .wrapping_add(input.section_count)
        .wrapping_add(input.sample_count);
    if population < rule.floor || population > rule.ceiling {
        return None;
    }
    let folded = lane ^ rule.mask.rotate_left((rule.relation & 31) as u32) ^ input.flag_word as u64;
    let threshold = ((rule.weight as u64) << 4) | (rule.relation as u64 & 0x0f);
    if (folded & 0xff) <= threshold {
        Some(RuleHit {
            rule_id: rule.id,
            severity: 1 + (rule.weight % 9),
            subject: (folded as u32) ^ ((population as u32) << 16),
            message_id: rule.floor ^ rule.ceiling ^ rule.id,
            evidence: folded,
        })
    } else {
        None
    }
}

